// --- PNG encoding -------------------------------------------------------------

function crc32(buf) {
  let c,
    crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) {
    c = (crc ^ buf[n]) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function toPng(name, art, colors = {}) {
  if (!art) throw new Error(`${name}: missing art`);
  const palette = { ...PALETTE, ...colors };
  const rows = art.trim().split("\n");
  const height = rows.length;
  const width = rows[0].length;
  const raw = Buffer.alloc((width * 4 + 1) * height);

  rows.forEach((row, y) => {
    if (row.length !== width) {
      throw new Error(`${name}: row ${y} is ${row.length} wide, expected ${width}`);
    }
    raw[y * (width * 4 + 1)] = 0; // filter: none
    [...row].forEach((ch, x) => {
      if (ch === ".") return; // stays transparent (zeroed)
      const hex = palette[ch];
      if (!hex) throw new Error(`${name}: unknown palette char "${ch}"`);
      const i = y * (width * 4 + 1) + 1 + x * 4;
      raw[i] = parseInt(hex.slice(0, 2), 16);
      raw[i + 1] = parseInt(hex.slice(2, 4), 16);
      raw[i + 2] = parseInt(hex.slice(4, 6), 16);
      raw[i + 3] = 255;
    });
  });

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

for (const [name, { art, colors }] of Object.entries(SPRITES)) {
  const file = join(RP, `${name}.png`);
  if (existsSync(file) && !force) {
    console.log(`skip   ${file}`);
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, toPng(name, art, colors));
  console.log(`wrote  ${file}`);
}
